/**
 * Build the standalone dsh-handsoff bundle from the two package sources.
 *
 * Outputs (all committed so git installs need no build scripts):
 *   lib/index.js   — host store plugin   (row `dsh-handsoff`)
 *   lib/host.js    — Remote controller   (row `dsh-handsoff/host`)
 *   client.js      — ModuleLoader-wrapped browser half: mounts the generated
 *                    sessionOrchestrator namespace, then registers the
 *                    HandsOff settings page.
 *
 * Externals: every @deepseek-ai/* runtime module plus react/react-dom are
 * provided by the dsh runtime (host process) and the web client module
 * registry (browser); zod is bundled in.
 *
 * Usage: node scripts/build-standalone.mjs
 */
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ORCH_SRC = join(ROOT, 'packages/orchestrator/session-orchestrator/src')
const UI_SRC = join(ROOT, 'packages/client/ui-settings-session-orchestrator/src')
const TYPERT_CLIENT = join(ROOT, 'standalone/vendor/typert.remote-client.js')
const BUNDLE_ID = 'dsh-handsoff'

// Browser services the merged half requires from the web composition.
// (The orchestrator module itself is no longer listed: its namespace is
// mounted inside this same apply, before the settings page reads it.)
export const CLIENT_INJECT = [
  '@deepseek-ai/dsh-api-session-controller',
  '@deepseek-ai/dsh-client-locale',
  '@deepseek-ai/dsh-client-ui-layout',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-renderer',
  '@deepseek-ai/dsh-client-ui-settings',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-workspace',
]

const harnessRequire = createRequire('C:/Users/16391/Desktop/home/harness-session/package.json')
const esbuild = harnessRequire('esbuild')
const zodDir = dirname(harnessRequire.resolve('zod/package.json'))
const { build } = esbuild

const SHARED = {
  bundle: true,
  legalComments: 'none',
  logLevel: 'warning',
  alias: { zod: zodDir },
}

// ---- host: store plugin ---------------------------------------------------
mkdirSync(join(ROOT, 'lib'), { recursive: true })
const indexBuild = await build({
  ...SHARED,
  entryPoints: [join(ORCH_SRC, 'index.ts')],
  format: 'esm',
  platform: 'node',
  target: 'node22',
  external: ['@deepseek-ai/*'],
  write: false,
})
writeFileSync(join(ROOT, 'lib/index.js'), indexBuild.outputFiles[0].text)
console.log('lib/index.js built')

// ---- host: Remote controller ---------------------------------------------
const hostBuild = await build({
  ...SHARED,
  entryPoints: [join(ORCH_SRC, 'remote.ts')],
  format: 'esm',
  platform: 'node',
  target: 'node22',
  external: ['@deepseek-ai/*'],
  write: false,
})
writeFileSync(join(ROOT, 'lib/host.js'), hostBuild.outputFiles[0].text)
console.log('lib/host.js built')

// ---- browser: merged client half ------------------------------------------
const entryDir = join(ROOT, 'standalone/.build')
mkdirSync(entryDir, { recursive: true })
const entry = join(entryDir, 'client-entry.mjs')
writeFileSync(
  entry,
  `// Generated by scripts/build-standalone.mjs — do not edit.
import typertRemote from '../vendor/typert.remote-client.js'
import * as handsoffUi from '${UI_SRC.replace(/\\/g, '/')}/client/index.ts'

export const inject = ${JSON.stringify(CLIENT_INJECT)}

export async function apply(ctx) {
  const disposeRemote = await ctx.remote.$mount(typertRemote)
  handsoffUi.apply(ctx)
  return async () => {
    await disposeRemote()
  }
}
`,
)

const raw = await build({
  ...SHARED,
  entryPoints: [entry],
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ['@deepseek-ai/*', 'react', 'react-dom', 'react/jsx-runtime'],
  loader: { '.css': 'local-css' },
  // local-css still emits a stylesheet output; an outfile is required for
  // esbuild to plan it even with write:false.
  outfile: join(entryDir, 'client.raw.js'),
  write: false,
})

const jsOut = raw.outputFiles.find((f) => f.path.endsWith('.js'))
const cssOut = raw.outputFiles.find((f) => f.path.endsWith('.css'))

const banner = `window.__ModuleLoader__.load({
	id: ${JSON.stringify(BUNDLE_ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
`
// The in-tree tsdown client face injects each CSS module as a <style> tag at
// import time; mirror that for the whole aggregated stylesheet.
const cssInject = cssOut
  ? `
	try {
		const tag = document.createElement("style");
		tag.setAttribute("data-dsh-handsoff", "");
		tag.textContent = ${JSON.stringify(cssOut.text)};
		document.head.appendChild(tag);
	} catch {
	}
`
  : ''
const footer = `
		return module.exports;
	}
});
`
const wrapped = `${banner}${cssInject}${jsOut.text}${footer}`
writeFileSync(join(ROOT, 'client.js'), wrapped)
console.log(`client.js built (${wrapped.length} bytes${cssOut ? `, css ${cssOut.text.length} bytes` : ', no css'})`)
